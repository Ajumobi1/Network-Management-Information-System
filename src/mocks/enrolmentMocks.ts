export const mockEnrollees: EnrolleeRecord[] = seedRecords.map((record, index) => ({
  ...record,
  id: `enrollee-${index + 1}`,
  fingerprint: buildFingerprint(record.policyNumber, record.period),
  createdAt: now,
  updatedAt: now,
}));

function matchesFilter(record: EnrolleeRecord, filters: EnrolmentFilters): boolean {
  const query = filters.search?.trim().toLowerCase() || '';
  const searchable = [
    record.policyNumber,
    record.firstName,
    record.lastName,
    record.providerName,
    record.providerCode,
    record.lga,
    record.state,
    record.senatorialDistrict,
  ].filter(Boolean).join(' ').toLowerCase();

  return (!query || searchable.includes(query))
    && (!filters.sector || filters.sector === 'all' || record.sector === filters.sector)
    && (!filters.category || filters.category === 'all' || record.category === filters.category)
    && (!filters.gender || filters.gender === 'all' || record.gender === filters.gender)
    && (!filters.state || filters.state === 'all' || record.state === filters.state)
    && (!filters.lga || filters.lga === 'all' || record.lga === filters.lga)
    && (!filters.senatorialDistrict || filters.senatorialDistrict === 'all' || record.senatorialDistrict === filters.senatorialDistrict)
    && (!filters.providerId || filters.providerId === 'all' || record.providerId === filters.providerId)
    && (!filters.period || filters.period === 'all' || record.period === filters.period)
    && (!filters.year || record.reportingYear === filters.year)
    && (!filters.month || record.reportingMonth === filters.month);
}

export async function getEnrolleesMock(filters: EnrolmentFilters = {}): Promise<EnrolleeRecord[]> {
  return mockEnrollees.filter(record => matchesFilter(record, filters));
}

export async function getEnrolleeByIdMock(id: string): Promise<EnrolleeRecord> {
  const record = mockEnrollees.find(item => item.id === id);
  if (!record) throw new Error('Enrollee record not found');
  return record;
}

export async function insertEnrolleesMock(records: EnrolleeRecord[]): Promise<EnrolleeRecord[]> {
  const existingFingerprints = new Set(mockEnrollees.map(record => record.fingerprint));
  const inserted: EnrolleeRecord[] = [];

  records.forEach((record, index) => {
    if (existingFingerprints.has(record.fingerprint)) return;
    const created: EnrolleeRecord = {
      ...record,
      id: record.id || `enrollee-${Date.now()}-${index}`,
      createdAt: record.createdAt || new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
    mockEnrollees.unshift(created);
    existingFingerprints.add(created.fingerprint);
    inserted.push(created);
  });

  return inserted;
}
